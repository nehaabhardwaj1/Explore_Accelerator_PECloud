def normalize_countries(raw: str) -> list:
    if not raw or not raw.strip():
        return []
    codes = []
    for part in raw.replace(",", ";").split(";"):
        p = part.strip().lower()
        code = _COUNTRY_NORM.get(p) or p.upper()[:2]
        if code and code not in codes:
            codes.append(code)
    return codes


